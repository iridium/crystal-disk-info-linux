#!/usr/bin/env python3
"""Produce AtaSmartCore.cpp from upstream AtaSmart.cpp.

Upstream AtaSmart.cpp mixes portable logic (identify parsing, vendor
detection, life/health evaluation) with Windows device I/O. We keep every
function verbatim except the ones that talk to Windows drivers; those are
re-implemented for Linux in core/AtaSmartLinux.cpp.
"""
import re
import sys

# CAtaSmart members implemented (or stubbed) for Linux elsewhere.
REPLACED = re.compile(r"""^(
      CAtaSmart | ~CAtaSmart | Init | Compare\w+ | WakeUp | GetDiskInfo
    | GetIoCtrlHandle\w* | \w+Pd | CreateWorldMutex | \w+MutexJMicron
    | DoIdentifyDeviceNVMe\w* | GetSmartAttributeNVMe\w* | GetNvMeIdentifyControllerData
    | isRealtekProduct | Realtek\w+ | GetScsiPath | GetScsiAddress
    | \w+Scsi | \w+Sat | \w+Si | \w+Wmi | \w*Csmi\w* | \w*MegaRAID\w*
    | \w*JMS\d\w* | \w*JMB\d\w*
)$""", re.X)

FUNC_START = re.compile(r"^(?:[A-Za-z_][\w\s\*&:<>,]*?\s)?CAtaSmart::(~?\w+)\s*\(")


def strip_code(line, state):
    """Return the line with strings, chars and comments blanked, tracking /* */."""
    out = []
    i = 0
    while i < len(line):
        c = line[i]
        if state["block"]:
            if line.startswith("*/", i):
                state["block"] = False
                i += 2
            else:
                i += 1
            continue
        if line.startswith("//", i):
            break
        if line.startswith("/*", i):
            state["block"] = True
            i += 2
            continue
        if c in "\"'":
            q = c
            i += 1
            while i < len(line) and line[i] != q:
                i += 2 if line[i] == "\\" else 1
            i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def main(src, dst):
    with open(src, encoding="utf-8-sig") as f:
        lines = f.read().split("\n")

    out = []
    state = {"block": False}
    i = 0
    removed = []
    while i < len(lines):
        line = lines[i]
        m = FUNC_START.match(line) if not state["block"] else None
        if m and REPLACED.match(m.group(1)):
            # Skip through the matching close brace of the function body.
            depth = 0
            seen_open = False
            while i < len(lines):
                code = strip_code(lines[i], state)
                depth += code.count("{") - code.count("}")
                if "{" in code:
                    seen_open = True
                i += 1
                if seen_open and depth <= 0:
                    break
            removed.append(m.group(1))
            continue
        strip_code(line, state)
        out.append(line)
        i += 1

    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/extract_core.py from upstream AtaSmart.cpp. Do not edit.\n")
        f.write("\n".join(out))
    sys.stderr.write("extract_core: replaced %d functions\n" % len(removed))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
